#!/usr/bin/env python3
"""Copies the feature list from support/features.json into README.md and the website.

    scripts/sync-features.py           rewrite whatever is stale
    scripts/sync-features.py --check   write nothing; exit 1 when an output is stale (for CI)

Three outputs, all from the one source:

- README.md, between the README markers below: a count line, then per group one table per status
  with no status column. A status no feature has is left out. Everything outside the markers is
  hand-written and left alone.
- site/index.html, between the start marker's comment and the end marker: the static copy of the
  feature list that readers without JavaScript and search engines see, one section per status
  that has features. The start comment's own text is kept. The markup is the same that
  renderFeatures in site/main.js draws, so a redraw moves nothing. When
  one of them changes, change the other to match. If the page's list uses a tag or class this
  script does not write, the script stops instead of writing over that work. The page's status
  chips that carry data-feature="<id>" also get that feature's status and label.
- site/data/features.json: a byte-for-byte copy of the source, which site/main.js reads.

Exit status: 0 when everything is in sync or was rewritten, 1 when --check finds a stale output,
2 when the data, a marker, a chip or the page's list markup is wrong. A problem in one output does
not stop the others from being checked or written.

Standard library only, Python 3.9 or later.
"""

import argparse
import html
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "support" / "features.json"
README = ROOT / "README.md"
SITE_PAGE = ROOT / "site" / "index.html"
SITE_COPY = ROOT / "site" / "data" / "features.json"

START = "<!-- features:start -->"
END = "<!-- features:end -->"
NOTICE = (
    "<!-- Generated by scripts/sync-features.py from support/features.json. "
    "Edit the JSON, then run the script. -->"
)

# The page's start marker is a comment that carries its own note, so the page matches on this
# prefix and keeps the rest of that comment as it is.
PAGE_START = "<!-- features:start"

# The statuses support/features.json may use, in the order every output lists them.
STATUS_LABELS = {
    "available": "Available",
    "in-progress": "In progress",
    "planned": "Planned",
}

# What each status means, as the website's legend says it. Keep in step with DEFINITION in
# site/main.js.
DEFINITIONS = {
    "available": "Works in the app today.",
    "in-progress": "Code exists or is being written. Not usable in the app yet.",
    "planned": "On the list. Not usable in the app yet.",
}

MONTHS = (
    "January February March April May June July August September October November December".split()
)


class DataError(Exception):
    """The source data, a marker or a chip is not in the shape this script expects."""


def relative(path):
    return path.relative_to(ROOT).as_posix()


def require_text(value, where):
    if not isinstance(value, str) or not value.strip():
        raise DataError(f"{where} must be a non-empty string")
    return value.strip()


def load_groups(raw):
    """Parses and checks the source. Returns (updated, [(group title, [feature dict])])."""
    try:
        data = json.loads(raw)
    except ValueError as error:
        raise DataError(f"{relative(SOURCE)} is not valid JSON: {error}") from None
    if not isinstance(data, dict):
        raise DataError(f"{relative(SOURCE)} must hold a JSON object")
    updated = require_text(data.get("updated"), "updated")
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", updated) or not 1 <= int(updated[5:7]) <= 12:
        raise DataError(f"updated {updated!r} must be a date written as YYYY-MM-DD")
    groups = data.get("groups")
    if not isinstance(groups, list) or not groups:
        raise DataError("groups must be a non-empty list")

    seen = set()
    parsed = []
    for g, group in enumerate(groups):
        if not isinstance(group, dict):
            raise DataError(f"groups[{g}] must be an object")
        title = require_text(group.get("title"), f"groups[{g}].title")
        features = group.get("features")
        if not isinstance(features, list) or not features:
            raise DataError(f"groups[{g}].features must be a non-empty list")
        rows = []
        for f, feature in enumerate(features):
            where = f"groups[{g}].features[{f}]"
            if not isinstance(feature, dict):
                raise DataError(f"{where} must be an object")
            feature_id = require_text(feature.get("id"), f"{where}.id")
            if feature_id in seen:
                raise DataError(f"{where}.id {feature_id!r} is used twice")
            seen.add(feature_id)
            status = require_text(feature.get("status"), f"{where}.status")
            if status not in STATUS_LABELS:
                allowed = ", ".join(STATUS_LABELS)
                raise DataError(f"{where}.status {status!r} is not one of: {allowed}")
            rows.append(
                {
                    "id": feature_id,
                    "title": require_text(feature.get("title"), f"{where}.title"),
                    "summary": require_text(feature.get("summary"), f"{where}.summary"),
                    "status": status,
                }
            )
        parsed.append((title, rows))
    return updated, parsed


def count(rows):
    """Returns {status: number of rows with it}, in STATUS_LABELS order."""
    counts = {status: 0 for status in STATUS_LABELS}
    for row in rows:
        counts[row["status"]] += 1
    return counts


def every_row(groups):
    return [row for _, rows in groups for row in rows]


def splice(text, start, end, block, path):
    """Returns text with everything from the start marker to the end marker replaced by block."""
    for marker in (start, end):
        found = text.count(marker)
        if found != 1:
            raise DataError(f"{relative(path)} must hold {marker} exactly once, found {found}")
    first = text.index(start)
    last = text.index(end) + len(end)
    if last < first:
        raise DataError(f"{relative(path)} has {end} before {start}")
    return text[:first] + block + text[last:]


# README.md


def cell(text):
    """Makes text safe inside one Markdown table cell."""
    text = " ".join(text.split())
    return text.replace("&", "&amp;").replace("<", "&lt;").replace("|", "\\|")


def join_words(parts):
    if len(parts) == 1:
        return parts[0]
    return ", ".join(parts[:-1]) + " and " + parts[-1]


def summary_line(updated, groups):
    """Leads with the statuses that have features and leaves out the ones that have none.

    "As of <date>, 10 of 19 features are in progress and 9 are planned. None is usable in an app
    yet." Once a feature is available: "As of <date>, 1 of 19 features is available, ..."
    """
    counts = count(every_row(groups))
    total = sum(counts.values())
    parts = []
    for status, n in counts.items():
        if n:
            verb = "is" if n == 1 else "are"
            parts.append(f"{n} {verb} {STATUS_LABELS[status].lower()}")
    noun = "feature" if total == 1 else "features"
    first, _, rest = parts[0].partition(" ")
    parts[0] = f"{first} of {total} {noun} {rest}"
    line = f"As of {updated}, {join_words(parts)}."
    if not counts["available"]:
        line += " None is usable in an app yet."
    return line


def render_readme_block(updated, groups):
    lines = [START, NOTICE, "", summary_line(updated, groups)]
    for title, rows in groups:
        lines += ["", f"### {cell(title)}"]
        for status, label in STATUS_LABELS.items():
            matching = [row for row in rows if row["status"] == status]
            if not matching:
                continue
            lines += ["", f"| {label} | What it does |", "|---|---|"]
            lines += [f"| {cell(row['title'])} | {cell(row['summary'])} |" for row in matching]
    lines += ["", END]
    return "\n".join(lines)


# site/index.html. Mirrors renderFeatures in site/main.js, one element per line.


def text(value):
    return html.escape(value, quote=True)


def render_page_block(start, updated, groups):
    """One section per status, in STATUS_LABELS order. A status no feature has is left out."""
    rows = every_row(groups)
    day = f"{int(updated[8:10])} {MONTHS[int(updated[5:7]) - 1]} {updated[:4]}"
    lines = [
        start,
        f'<p class="status-updated">Updated <time datetime="{text(updated)}">{day}</time></p>',
        '<div class="feature-groups">',
    ]
    for status, label in STATUS_LABELS.items():
        matching = [row for row in rows if row["status"] == status]
        if not matching:
            continue
        group_id = f"fs-{status}"
        noun = "feature" if len(matching) == 1 else "features"
        lines += [
            f'<section class="feature-group" data-status="{status}" aria-labelledby="{group_id}">',
            f'<header class="feature-group-head"><h3 id="{group_id}">'
            f'<span class="status-mark" aria-hidden="true"></span>{text(label)}</h3>'
            f"<p>{len(matching)} {noun}</p></header>",
            f'<p class="feature-group-def">{text(DEFINITIONS[status])}</p>',
            '<ul class="feature-list">',
        ]
        lines += [
            f'<li class="feature"><h4>{text(row["title"])}</h4><p>{text(row["summary"])}</p></li>'
            for row in matching
        ]
        lines += ["</ul>", "</section>"]
    lines += ["</div>", END]
    return "\n".join(lines)


# A status chip that names a feature: <span class="chip" data-feature="id" data-status="s">
# <span class="chip-dot" aria-hidden="true"></span>Label</span>, attributes in any order.
FEATURE_CHIP = re.compile(
    r'(?P<open><span\b(?=[^>]*\bclass="chip")(?=[^>]*\bdata-feature="(?P<id>[^"]*)")[^>]*>)'
    r'(?P<dot><span class="chip-dot" aria-hidden="true"></span>)'
    r"(?P<label>[^<]*)</span>"
)
STATUS_ATTRIBUTE = re.compile(r'\bdata-status="[^"]*"')


def update_chips(page, statuses):
    """Gives every chip with data-feature the status and label of that feature."""

    def rewrite(match):
        feature_id = match.group("id")
        if feature_id not in statuses:
            raise DataError(
                f'{relative(SITE_PAGE)} has a chip with data-feature="{feature_id}", '
                f"which is not an id in {relative(SOURCE)}"
            )
        status = statuses[feature_id]
        opening = match.group("open")
        wanted = f'data-status="{status}"'
        if STATUS_ATTRIBUTE.search(opening):
            opening = STATUS_ATTRIBUTE.sub(wanted, opening, count=1)
        else:
            opening = opening[:-1] + f" {wanted}>"
        return f"{opening}{match.group('dot')}{text(STATUS_LABELS[status])}</span>"

    return FEATURE_CHIP.sub(rewrite, page)


OPENING_TAG = re.compile(r'<([a-z][a-z0-9]*)\b(?:[^>]*?\bclass="([^"]*)")?[^>]*>')


def markup(block):
    """The set of (tag, class) pairs a block uses. Data changes keep it; a redesign changes it."""
    return {(tag, " ".join(sorted(classes.split()))) for tag, classes in OPENING_TAG.findall(block)}


def check_markup(current, wanted):
    """Refuses to replace a static list whose markup this script does not write.

    Someone may have redesigned the list in index.html and main.js by hand. Writing over it would
    undo that work, so stop and say what differs instead. An empty block is there to be filled.
    """
    have, write = markup(current), markup(wanted)
    if not have or have == write:
        return

    def show(pairs):
        return ", ".join(f'<{tag} class="{cls}">' if cls else f"<{tag}>" for tag, cls in sorted(pairs))

    details = []
    if have - write:
        details.append(f"the page uses {show(have - write)}")
    if write - have:
        details.append(f"this script writes {show(write - have)}")
    raise DataError(
        f"the static feature list in {relative(SITE_PAGE)} uses markup this script does not write: "
        f"{'; '.join(details)}. Change render_page_block in scripts/sync-features.py to match "
        "renderFeatures in site/main.js, then run the script again."
    )


def render_page(page, updated, groups):
    """Returns the page with the static feature list and the section chips brought up to date."""
    first = page.find(PAGE_START)
    if first < 0 or page.count(PAGE_START) != 1:
        found = page.count(PAGE_START)
        raise DataError(f"{relative(SITE_PAGE)} must hold {PAGE_START} exactly once, found {found}")
    # The start comment carries a note, so the marker spans to the end of that comment.
    close = page.find("-->", first)
    start = page[first : close + len("-->")] if close >= 0 else ""
    if not start or END in start:
        raise DataError(f"{relative(SITE_PAGE)} never closes the {PAGE_START} comment")
    block = render_page_block(start, updated, groups)
    wanted = splice(page, start, END, block, SITE_PAGE)
    # splice checked the markers, so the old block runs from the start comment to the end marker.
    check_markup(page[first : page.index(END) + len(END)], block)
    # The block's own chips carry no data-feature, so this touches only the section chips.
    return update_chips(wanted, {row["id"]: row["status"] for row in every_row(groups)})


def write_atomically(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(handle, "wb") as out:
            out.write(data)
        os.chmod(temp, 0o644)
        os.replace(temp, path)
    except BaseException:
        os.unlink(temp)
        raise


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Write the feature list from support/features.json into README.md, site/index.html "
            "and site/data."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 when README.md, site/index.html or site/data/features.json is stale",
    )
    args = parser.parse_args()

    def fail(error):
        print(f"sync-features: {error}", file=sys.stderr)

    try:
        source = SOURCE.read_bytes()
        updated, groups = load_groups(source.decode("utf-8"))
    except (OSError, UnicodeDecodeError, DataError) as error:
        fail(error)
        return 2

    # Each output is (path, wanted bytes, current bytes or None). One output's problem does not
    # stop the others from being checked or written.
    outputs = [(SITE_COPY, source, SITE_COPY.read_bytes() if SITE_COPY.exists() else None)]
    broken = False
    for path, render in (
        (README, lambda text: splice(text, START, END, render_readme_block(updated, groups), README)),
        (SITE_PAGE, lambda text: render_page(text, updated, groups)),
    ):
        try:
            current = path.read_text(encoding="utf-8")
            outputs.insert(-1, (path, render(current).encode("utf-8"), current.encode("utf-8")))
        except (OSError, UnicodeDecodeError, DataError) as error:
            fail(error)
            broken = True

    stale = [(path, wanted) for path, wanted, current in outputs if wanted != current]
    if args.check:
        for path, _ in stale:
            fail(f"{relative(path)} is stale. Run scripts/sync-features.py.")
        if not stale and not broken:
            names = ", ".join(relative(path) for path, _, _ in outputs)
            print(f"sync-features: OK, {names} match support/features.json")
        return 2 if broken else 1 if stale else 0

    for path, wanted in stale:
        write_atomically(path, wanted)
        print(f"sync-features: wrote {relative(path)}")
    if not stale and not broken:
        print("sync-features: already in sync")
    return 2 if broken else 0


if __name__ == "__main__":
    sys.exit(main())
