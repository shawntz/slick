import AppKit
import Foundation
import Kit
import KitTesting
import Synchronization
import Testing

@testable import Platform

/// Every test uses its own private named pasteboard, released at the end. None touches the general
/// pasteboard, and none posts a keystroke: the poster only records.
@Suite(.timeLimit(.minutes(1))) struct PasteboardTests {
    let board = NSPasteboard(name: NSPasteboard.Name("test.platform.pasteboard.\(UUID().uuidString)"))
    let permissions = FakePermissions()
    let poster = RecordingKeystrokePoster()

    func makeService(
        frontmost: @escaping @Sendable () async -> Bool = { true }
    ) -> LivePasteboard {
        LivePasteboard(
            pasteboard: board, permissions: permissions, poster: poster, clock: FakeClock(),
            sourceApplication: { "com.example.frontmost" }, anotherAppIsFrontmost: frontmost,
            ownBundleID: "com.example.self", pollInterval: .milliseconds(20))
    }

    /// Plays another app writing the pasteboard, on the service's own queue.
    func otherAppWrites(
        _ service: LivePasteboard, text: String, markers: [String] = [], source: String? = nil
    ) async {
        await service.withPasteboard { board in
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            for marker in markers {
                item.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
            }
            if let source { item.setString(source, forType: NSPasteboard.PasteboardType(PasteboardMarkers.source)) }
            board.clearContents()
            board.writeObjects([item])
        }
    }

    /// Collects `count` entries, or what arrived before the limit.
    func collect(_ stream: AsyncStream<PasteboardEntry>, count: Int) -> Task<[PasteboardEntry], Never> {
        Task {
            var entries: [PasteboardEntry] = []
            for await entry in stream {
                entries.append(entry)
                if entries.count == count { break }
            }
            return entries
        }
    }

    @Test func copyMarksItsWritesTransientWithThisAppAsSource() async {
        defer { board.releaseGlobally() }
        let service = makeService()
        let before = service.changeCount
        await service.copy("synthetic copy")
        #expect(service.changeCount != before)
        let types = await service.withPasteboard { board in (board.types ?? []).map(\.rawValue) }
        #expect(types.contains(PasteboardMarkers.transient))
        #expect(!types.contains(PasteboardMarkers.concealed))
        let source = await service.withPasteboard { board in
            board.string(forType: NSPasteboard.PasteboardType(PasteboardMarkers.source))
        }
        #expect(source == "com.example.self")
        // This app's own writes stay readable.
        let entry = await service.read()
        #expect(entry?.plainText == "synthetic copy")
        #expect(entry?.sourceBundleID == "com.example.self")

        await service.copy(.text("synthetic secret"), options: .concealed)
        let concealed = await service.withPasteboard { board in (board.types ?? []).map(\.rawValue) }
        #expect(concealed.contains(PasteboardMarkers.concealed))
        #expect(await service.read() == nil)
    }

    @Test func entriesReportOtherAppsAndSkipMarkedAndOwnWrites() async {
        defer { board.releaseGlobally() }
        let service = makeService()
        let consumer = collect(service.entries(), count: 2)
        await service.copy("written by this app")
        await otherAppWrites(service, text: "hidden", markers: [PasteboardMarkers.concealed])
        try? await Task.sleep(for: .milliseconds(60))
        await otherAppWrites(service, text: "passing", markers: [PasteboardMarkers.transient])
        try? await Task.sleep(for: .milliseconds(60))
        await otherAppWrites(service, text: "synced", markers: [PasteboardMarkers.autoGenerated])
        try? await Task.sleep(for: .milliseconds(60))
        await otherAppWrites(service, text: "legacy", markers: ["de.petermaurer.TransientPasteboardType"])
        try? await Task.sleep(for: .milliseconds(60))
        await otherAppWrites(service, text: "first visible", source: "com.example.editor")
        try? await Task.sleep(for: .milliseconds(60))
        await otherAppWrites(service, text: "second visible")
        let entries = await boundedValue(of: consumer)
        #expect(entries.map(\.plainText) == ["first visible", "second visible"])
        #expect(entries.first?.sourceBundleID == "com.example.editor")
        // Without a source marker, the frontmost app is the source.
        #expect(entries.last?.sourceBundleID == "com.example.frontmost")
    }

    @Test func pollingRunsOnlyWhileAStreamIsOpen() async throws {
        defer { board.releaseGlobally() }
        let service = makeService()
        #expect(!service.isPolling)
        let first = service.entries()
        let second = service.entries()
        #expect(service.isPolling)
        let consumers = [
            Task {
                for await _ in first {}
            },
            Task {
                for await _ in second {}
            },
        ]
        consumers[0].cancel()
        await boundedValue(of: consumers[0])
        try await Task.sleep(for: .milliseconds(20))
        #expect(service.isPolling)
        consumers[1].cancel()
        await boundedValue(of: consumers[1])
        try await waitUntil { !service.isPolling }
    }

    @Test func nothingIsReadWithoutThePasteboardPermission() async {
        defer { board.releaseGlobally() }
        permissions.set(.pasteboard, to: .notDetermined)
        let service = makeService()
        let consumer = collect(service.entries(), count: 1)
        await otherAppWrites(service, text: "unread")
        try? await Task.sleep(for: .milliseconds(80))
        permissions.set(.pasteboard, to: .granted)
        await otherAppWrites(service, text: "read")
        #expect(await boundedValue(of: consumer).map(\.plainText) == ["read"])
    }

    @Test func pasteWritesThenSendsCommandVAndLeftPresses() async throws {
        defer { board.releaseGlobally() }
        let service = makeService()
        let closed = Closed()
        service.setPanelCloser { closed.mark() }
        try await service.paste(Expansion("a👍🏽 b", charactersAfterCursor: 2))
        #expect(closed.count == 1)
        #expect(poster.posted == [.paste, .key(KeyCombo(.leftArrow)), .key(KeyCombo(.leftArrow))])
        #expect(await service.read()?.plainText == "a👍🏽 b")
    }

    @Test func pasteWithoutAccessibilityLeavesTheContentAndSendsNothing() async {
        defer { board.releaseGlobally() }
        poster.isAllowed = false
        let service = makeService()
        await #expect(throws: PasteError.permissionMissing(.accessibility)) {
            try await service.paste("synthetic")
        }
        #expect(poster.posted.isEmpty)
        #expect(await service.read()?.plainText == "synthetic")
    }

    @Test func pasteGivesUpWhenNoOtherAppComesForward() async {
        defer { board.releaseGlobally() }
        let service = makeService(frontmost: { false })
        await #expect(throws: PasteError.targetDidNotActivate) {
            try await service.paste("synthetic")
        }
        #expect(poster.posted.isEmpty)
    }

    @Test func recentTextUsesTheRegisteredHistoryOrWhatTheServiceSaw() async {
        defer { board.releaseGlobally() }
        let service = makeService()
        await service.copy("older")
        await service.copy("newer")
        #expect(await service.recentText(offset: 0) == "newer")
        #expect(await service.recentText(offset: 1) == "older")
        #expect(await service.recentText(offset: 2) == nil)
        #expect(await service.recentText(offset: -1) == nil)

        // The history leaves out this app's own copies, so the current text comes first.
        service.setHistoryReader(StaticHistory(texts: ["from history"]))
        #expect(await service.recentText(offset: 0) == "newer")
        #expect(await service.recentText(offset: 1) == "from history")
        #expect(await service.recentText(offset: 2) == nil)
        service.setHistoryReader(nil)
        #expect(await service.recentText(offset: 0) == "newer")
    }

    @Test func recentTextCountsTheCurrentTextOnceWhenTheHistoryHoldsIt() async {
        defer { board.releaseGlobally() }
        let service = makeService()
        await otherAppWrites(service, text: "copied elsewhere")
        service.setHistoryReader(StaticHistory(texts: ["copied elsewhere", "before that"]))
        #expect(await service.recentText(offset: 0) == "copied elsewhere")
        #expect(await service.recentText(offset: 1) == "before that")
        #expect(await service.recentText(offset: 2) == nil)
    }

    @Test func everyKindOfContentRoundTrips() async throws {
        defer { board.releaseGlobally() }
        let service = makeService()
        let rtf = Data("{\\rtf1 synthetic}".utf8)
        await service.copy(.richText(rtf: rtf, plain: "synthetic"), options: [])
        #expect(await service.read()?.contents == [.richText(rtf: rtf, plain: "synthetic"), .text("synthetic")])

        let url = try #require(URL(string: "https://example.com/page"))
        await service.copy(.url(url), options: [])
        #expect(await service.read()?.contents == [.url(url), .text(url.absoluteString)])

        let folder = TemporaryFolder()
        let file = folder.url.appending(path: "sample.txt")
        await service.copy(.files([file, folder.url]), options: [])
        let files = await service.read()?.contents
        #expect(files == [.files([file, folder.url])])

        let png = Data([0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
        await service.copy(.image(png, typeIdentifier: "public.png"), options: [])
        #expect(await service.read()?.contents == [.image(png, typeIdentifier: "public.png")])
        withExtendedLifetime(folder) {}
    }

    /// A browser's copy carries HTML and plain text but no RTF. The HTML is never read: the plain
    /// text is kept. A copy of HTML alone gives no entry.
    @Test func htmlIsNeverReadAndItsPlainTextIsKept() async {
        defer { board.releaseGlobally() }
        let service = makeService()
        await service.withPasteboard { board in
            let item = NSPasteboardItem()
            item.setString("<b>synthetic</b>", forType: .html)
            item.setString("synthetic", forType: .string)
            board.clearContents()
            board.writeObjects([item])
        }
        #expect(await service.read()?.contents == [.text("synthetic")])

        await service.withPasteboard { board in
            board.clearContents()
            board.setString("<b>synthetic</b>", forType: .html)
        }
        #expect(await service.read() == nil)
    }

    @Test func richTextOverTheLimitKeepsOnlyThePlainText() async {
        defer { board.releaseGlobally() }
        let service = LivePasteboard(
            pasteboard: board, permissions: permissions, poster: poster, clock: FakeClock(),
            ownBundleID: "com.example.self", maximumRichTextBytes: 8)
        await service.withPasteboard { board in
            let item = NSPasteboardItem()
            item.setData(Data("{\\rtf1 synthetic}".utf8), forType: .rtf)
            item.setString("synthetic", forType: .string)
            board.clearContents()
            board.writeObjects([item])
        }
        #expect(await service.read()?.contents == [.text("synthetic")])
    }

    @Test func markersAreReadTheWayNspasteboardOrgDescribes() {
        #expect(PasteboardMarkers.verdict(for: ["public.utf8-plain-text"]).mayRecord)
        #expect(PasteboardMarkers.verdict(for: [PasteboardMarkers.concealed]).isConcealed)
        #expect(PasteboardMarkers.verdict(for: ["com.agilebits.onepassword"]).isConcealed)
        #expect(PasteboardMarkers.verdict(for: ["com.typeit4me.clipping"]).isTransient)
        #expect(PasteboardMarkers.verdict(for: [PasteboardMarkers.autoGenerated]).isAutoGenerated)
        #expect(!PasteboardMarkers.verdict(for: [PasteboardMarkers.transient]).mayRecord)
    }

    @Test func textIsSplitIntoWholeCharactersAndLineBreaks() {
        let pieces = CGEventKeystrokePoster.pieces(of: "ab\ncd", limit: 20)
        #expect(
            pieces == [
                .characters(Array("ab".utf16)), .lineBreak, .characters(Array("cd".utf16)),
            ])
        // A flag of two scalars is four UTF-16 units and is never split across events.
        let flags = String(repeating: "🇨🇭", count: 6)
        let split = CGEventKeystrokePoster.pieces(of: flags, limit: 10)
        #expect(split.count == 3)
        for piece in split {
            guard case .characters(let units) = piece else {
                Issue.record("unexpected line break")
                continue
            }
            #expect(units.count <= 10 && units.count % 4 == 0)
        }
        #expect(CGEventKeystrokePoster.flags(for: [.command, .shift]) == [.maskCommand, .maskShift])
    }
}

/// Counts how often the panel was closed.
nonisolated private final class Closed: Sendable {
    private let calls = Mutex(0)

    var count: Int { calls.withLock { $0 } }

    func mark() {
        calls.withLock { $0 += 1 }
    }
}

/// A clipboard history with fixed texts, newest first.
nonisolated private struct StaticHistory: ClipboardHistoryReader {
    let texts: [String]

    @concurrent func text(offset: Int) async -> String? {
        texts.indices.contains(offset) ? texts[offset] : nil
    }
}
