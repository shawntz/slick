import Foundation

/// The marker types clipboard tools put on the pasteboard, as nspasteboard.org describes them,
/// and the rules that decide which changes are recorded.
nonisolated public enum PasteboardMarkers {
    /// Secret content, such as a password. Never stored.
    public static let concealed = "org.nspasteboard.ConcealedType"
    /// Content that only passes through the pasteboard, such as a paste a tool performs. Never
    /// recorded.
    public static let transient = "org.nspasteboard.TransientType"
    /// Content an app wrote without the user asking, such as a sync. Never recorded.
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    /// The bundle ID of the app that wrote the content, as UTF-8 text.
    public static let source = "org.nspasteboard.source"

    /// Older markers some apps still write, with what they mean.
    static let legacyConcealed: Set<String> = ["com.agilebits.onepassword", "net.antelle.keeweb"]
    static let legacyTransient: Set<String> = [
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ]

    /// What the marker types on a pasteboard say about its contents.
    public struct Verdict: Hashable, Sendable {
        public var isConcealed: Bool
        public var isTransient: Bool
        public var isAutoGenerated: Bool

        /// True when a clipboard history may record the contents.
        public var mayRecord: Bool {
            !isConcealed && !isTransient && !isAutoGenerated
        }
    }

    /// Reads the markers among a pasteboard's types.
    public static func verdict(for types: [String]) -> Verdict {
        var verdict = Verdict(isConcealed: false, isTransient: false, isAutoGenerated: false)
        for type in types {
            if type == concealed || legacyConcealed.contains(type) { verdict.isConcealed = true }
            if type == transient || legacyTransient.contains(type) { verdict.isTransient = true }
            if type == autoGenerated { verdict.isAutoGenerated = true }
        }
        return verdict
    }
}
