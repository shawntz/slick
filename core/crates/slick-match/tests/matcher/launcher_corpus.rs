/// The corpus: titles plus, per title, whether it is an app.
pub struct LauncherCorpus {
    pub titles: Vec<String>,
    pub is_app: Vec<bool>,
    seen: HashSet<String>,
}

impl LauncherCorpus {
    fn add(&mut self, title: String, app: bool) {
        if self.seen.insert(title.to_lowercase()) {
            self.titles.push(title);
            self.is_app.push(app);
        }
    }
}

/// Builds the corpus deterministically. About 3,000 generated titles follow the fixed lists.
pub fn build() -> LauncherCorpus {
    let mut rng = Rng::new(42);
    let mut c = LauncherCorpus {
        titles: Vec::new(),
        is_app: Vec::new(),
        seen: HashSet::new(),
    };
    for a in APPS.iter().chain(APP_FIXTURES) {
        c.add(a.to_string(), true);
    }
    for p in PANES {
        c.add(format!("{p} Settings"), false);
        c.add(format!("Open {p} Settings"), false);
    }
    for s in SYSTEM.iter().chain(WINDOW).chain(SNIPPETS) {
        c.add(s.to_string(), false);
    }
    for e in ENGINES {
        c.add(format!("Search {e}"), false);
        c.add(format!("Open {e}"), false);
    }
    for (service, commands) in SERVICES {
        for command in commands.iter() {
            c.add(format!("{service}: {command}"), false);
            c.add(format!("{command} in {service}"), false);
        }
    }
    for first in FIRST {
        for _ in 0..4 {
            let last = LAST[rng.below(LAST.len())];
            c.add(format!("{first} {last}"), false);
        }
    }
    let target = APPS.len() + APP_FIXTURES.len() + 3_000 - FIXTURES.len();
    while c.titles.len() < target {
        let x = EXTENSIONS[rng.below(EXTENSIONS.len())];
        let v = VERBS[rng.below(VERBS.len())];
        let n = NOUNS[rng.below(NOUNS.len())];
        if rng.below(2) == 0 {
            c.add(format!("{v} {x} {n}"), false);
        } else {
            c.add(format!("{x}: {v} {n}"), false);
        }
    }
    for f in FIXTURES {
        c.add(f.to_string(), false);
    }
    c
}
